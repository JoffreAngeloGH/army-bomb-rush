// Extracts only the animated Material Line Icons (line-md) we use into src/data/line-md.ts,
// so the client bundle doesn't ship the full 1200-icon set.
// Usage: node scripts/gen-icons.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const set = require('@iconify-json/line-md/icons.json');

/** our icon name -> line-md icon name */
const wanted = {
  refresh: 'backup-restore',
  'arrow-right': 'arrow-right',
  play: 'play-filled',
  pause: 'pause',
  'volume-on': 'volume-high-filled',
  'volume-off': 'volume-high-off-filled',
  heart: 'heart-filled',
  trophy: 'star-pulsating-filled-loop',
  check: 'check-all',
  x: 'close',
  zap: 'speed-loop',
};

const out = {};
for (const [ours, theirs] of Object.entries(wanted)) {
  const icon = set.icons[theirs];
  if (!icon) throw new Error(`line-md has no icon "${theirs}"`);
  out[ours] = icon.body;
}

const src = `// Generated by scripts/gen-icons.mjs from @iconify-json/line-md (MIT). Do not edit by hand.
export const lineMd: Record<string, string> = ${JSON.stringify(out, null, 2)};
`;
writeFileSync(new URL('../src/data/line-md.ts', import.meta.url), src);
console.log(`wrote ${Object.keys(out).length} icons`);
